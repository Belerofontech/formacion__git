def suma(a: int, b: int) -> int:
    """Just add two numbers, a and b.

    Args:
        a (int): number 1.
        b (int): number 2.

    Returns:
        int: result.
    """
    return a + b


def resta(a: int, b: int) -> int:
    """_summary_

    Args:
        a (int): minuendo.
        b (int): sustraendo.

    Returns:
        int: resultado.
    """
    return a - b
