def suma(a: int, b: int) -> int:
    """_summary_

    Args:
        a (int): primer número
        b (int): segundo número

    Returns:
        int: suma entre a y b
    """
    return a + b


def resta(a: int, b: int) -> int:
    """_summary_

    Args:
        a (int): primer número
        b (int): segundo número

    Returns:
        int: resta entre a y b
    """
    return a - b
