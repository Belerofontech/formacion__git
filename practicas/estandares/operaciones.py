def suma(a: int, b: int) -> int:
    """Función que realiza una suma

    Args:
        a (int): sumando 1
        b (int): sumando 2

    Returns:
        int: resultado
    """
    return a + b
def resta(a: int, b: int) -> int:
    """Función que realiza una resta

    Args:
        a (int): minuendo
        b (int): sustrando

    Returns:
        int: resutado
    """
    return a - b
