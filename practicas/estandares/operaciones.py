def suma(a: int, b: int) -> int:
    """Función que realiza una suma.

    Args:
        a (int): sumando 1.
        b (int): sumando 2.

    Returns:
        int: resultado.
    """
    return a + b


def resta(a: int, b: int) -> int:
    """_summary_

    Args:
        a (int): minuendo.
        b (int): sustraendo.

    Returns:
        int: resultado.
    """
    return a - b
